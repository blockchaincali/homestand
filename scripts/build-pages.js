'use strict';
// Builds the static browser edition of HOMESTAND (GitHub Pages) into dist/.
// The same room server the Node build runs (src/rooms.js + the engine) is bundled into the page,
// and the client talks to it through an in-page socket, so every mode against the AI plays
// exactly as it does online. Online rooms (versus, co-op, Vatar) still need `npm start`.
// Usage: node scripts/build-pages.js   then serve dist/ (works from any sub-path).
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..'),pub=path.join(root,'public'),out=path.join(root,'dist');

// ---------- 1. Bundle the CommonJS room server for the browser ----------
// UMD files the page already loads as globals are shared, not duplicated.
const GLOBALS={[path.join(pub,'maps.js')]:'HomestandMaps',[path.join(pub,'catalog.js')]:'HomestandCatalog'};
const modules=new Map();
function resolve(from,request){
 if(!request.startsWith('.'))throw new Error(`Browser bundle cannot use "${request}" (required from ${path.relative(root,from)})`);
 const base=path.resolve(path.dirname(from),request);
 for(const file of [base,base+'.js'])if(fs.existsSync(file)&&fs.statSync(file).isFile())return file;
 throw new Error(`Cannot resolve ${request} from ${from}`);
}
function add(file){
 if(modules.has(file)||GLOBALS[file])return;
 const source=fs.readFileSync(file,'utf8'),deps={};
 modules.set(file,{source,deps});
 for(const [,request] of source.matchAll(/require\(\s*['"]([^'"]+)['"]\s*\)/g)){const target=resolve(file,request);deps[request]=target;add(target)}
}
const entry=path.join(root,'src','rooms.js');add(entry);
const id=file=>JSON.stringify(path.relative(root,file).split(path.sep).join('/'));
const bundle=`// HOMESTAND browser edition: room server + engine (generated by scripts/build-pages.js).
(function(){'use strict';
const defs={},cache={};
const globals=${JSON.stringify(Object.fromEntries(Object.entries(GLOBALS).map(([f,g])=>[path.relative(root,f).split(path.sep).join('/'),g])))};
function load(name){if(globals[name])return globalThis[globals[name]];if(cache[name])return cache[name].exports;const module=cache[name]={exports:{}};defs[name].fn(module,module.exports,r=>load(defs[name].deps[r]));return module.exports}
${[...modules].map(([file,{source,deps}])=>`defs[${id(file)}]={deps:${JSON.stringify(Object.fromEntries(Object.entries(deps).map(([r,t])=>[r,path.relative(root,t).split(path.sep).join('/')])))},fn:function(module,exports,require){\n${source}\n}};`).join('\n')}
const {createHub}=load(${id(entry)});
const hub=createHub({maxCatchUp:1});setInterval(()=>hub.tick(performance.now()),50);
// A WebSocket look-alike. Messages cross on the microtask queue, so neither side re-enters the other.
class Socket{
 constructor(){
  this.readyState=0;this.bufferedAmount=0;
  const client=this;
  this.peer={readyState:1,send:text=>queueMicrotask(()=>{if(client.readyState===1)client.onmessage?.({data:text})}),close:()=>client.close()};
  setTimeout(()=>{this.readyState=1;this.onopen?.({})},0);
 }
 send(text){
  if(this.readyState!==1)return;
  let msg=null;try{msg=JSON.parse(text)}catch{}
  // Online rooms need other players on a server; say so instead of opening a lobby nobody can join.
  if(msg?.type==='create'&&(msg.mode==='pvp'||msg.coop===true))return queueMicrotask(()=>this.onmessage?.({data:JSON.stringify({type:'notice',message:'Online rooms need the live server. The browser edition plays against the AI.'})}));
  queueMicrotask(()=>hub.message(this.peer,text));
 }
 close(){if(this.readyState===3)return;this.readyState=3;this.peer.readyState=3;hub.close(this.peer);setTimeout(()=>this.onclose?.({}),0)}
}
Socket.CONNECTING=0;Socket.OPEN=1;Socket.CLOSING=2;Socket.CLOSED=3;
globalThis.HomestandLocal={Socket,hub,edition:'browser'};
})();
`;

// ---------- 2. Copy the client and make every path relative ----------
// GitHub Pages serves a project site from /<repo>/, so "/style.css" must become "style.css".
fs.rmSync(out,{recursive:true,force:true});
fs.cpSync(pub,out,{recursive:true});
fs.rmSync(path.join(out,'sw.js'),{force:true});
const vendor=path.join(out,'vendor');fs.mkdirSync(vendor,{recursive:true});
const three=path.join(root,'node_modules','three');
fs.copyFileSync(path.join(three,'build','three.module.min.js'),path.join(vendor,'three.module.js'));
fs.copyFileSync(path.join(three,'build','three.core.min.js'),path.join(vendor,'three.core.min.js'));
fs.copyFileSync(path.join(three,'build','three.core.min.js'),path.join(vendor,'three.core.js'));
fs.copyFileSync(path.join(three,'examples','jsm','utils','BufferGeometryUtils.js'),path.join(vendor,'BufferGeometryUtils.js'));
fs.writeFileSync(path.join(out,'local.js'),bundle);

const tops=fs.readdirSync(out).filter(n=>n!=='index.html').map(n=>n.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'));
const absolute=new RegExp(`(["'(=])/(${tops.join('|')})(?=[/"')?#]|$)`,'g');
let rewritten=0;
for(const file of walk(out)){
 if(!/\.(html|js|css|webmanifest)$/.test(file)||file.endsWith('local.js'))continue;
 const text=fs.readFileSync(file,'utf8');
 // Relative to the document for HTML/CSS; a module's own imports resolve against its own URL,
 // which sits at the site root here, so "./" works for both.
 const next=text.replace(absolute,(m,lead,name)=>{rewritten++;return lead+'./'+name}).replace(/href="\/"/g,'href="./"');
 if(next!==text)fs.writeFileSync(file,next);
}
// The install manifest must stay inside the project sub-path too.
const manifestFile=path.join(out,'manifest.webmanifest');
if(fs.existsSync(manifestFile)){const m=JSON.parse(fs.readFileSync(manifestFile,'utf8'));Object.assign(m,{id:'./',start_url:'./?source=app',scope:'./'});for(const icon of m.icons||[])icon.src=String(icon.src).replace(/^\//,'./');fs.writeFileSync(manifestFile,JSON.stringify(m,null,1))}
// Load the in-page server before the game script.
const indexFile=path.join(out,'index.html');
let index=fs.readFileSync(indexFile,'utf8');
if(!index.includes('<script src="./game.js" defer></script>'))throw new Error('index.html changed: cannot insert local.js');
index=index.replace('<script src="./game.js" defer></script>','<script src="./local.js" defer></script><script src="./game.js" defer></script>');
fs.writeFileSync(indexFile,index);
fs.copyFileSync(indexFile,path.join(out,'404.html'));
fs.writeFileSync(path.join(out,'.nojekyll'),'');

const leftovers=[...walk(out)].filter(f=>/\.(html|js|css)$/.test(f)).flatMap(f=>[...fs.readFileSync(f,'utf8').matchAll(/["'(]\/(vendor|assets|icons)\//g)].map(()=>path.relative(out,f)));
if(leftovers.length)throw new Error('Absolute paths left in: '+[...new Set(leftovers)].join(', '));
console.log(`HOMESTAND browser edition: ${modules.size} modules bundled, ${rewritten} paths made relative -> dist/`);

function* walk(dir){for(const e of fs.readdirSync(dir,{withFileTypes:true})){const p=path.join(dir,e.name);if(e.isDirectory())yield* walk(p);else yield p}}
